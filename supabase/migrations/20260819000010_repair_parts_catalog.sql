-- ============================================================================
-- Mano Mobile — repair spare-parts catalogue and the request/approval workflow
--
-- Until now both of these lived in browser localStorage (PartsContext), which
-- meant the catalogue existed only on the machine that typed it in: a
-- technician on their own phone saw an empty parts list, two browsers kept two
-- different stock counts, and clearing site data erased the lot. None of that
-- can support an approval workflow, whose whole point is that one person
-- requests and a different person approves.
--
-- This is deliberately SEPARATE from the retail inventory (accessories sold
-- over the counter). A screen consumed in a repair and a case sold to a
-- customer are counted, costed and reordered differently, and merging them
-- would make "stock" ambiguous in both directions.
--
-- Not to be confused with repair_parts_used (migration 3): that records what
-- was actually consumed on one job. This records what the shop stocks.
--
--   repair_parts              the catalogue — what we stock, at what cost
--     └─ repair_part_requests    a technician asking for N of one, and the
--                                admin approving or rejecting it
-- ============================================================================

-- ── Enums ───────────────────────────────────────────────────────────────────
-- Mirrors PART_CATEGORIES in PartsContext.tsx. An enum rather than free text so
-- a typo cannot quietly create a ninth category that no filter matches.

do $$ begin
  create type part_category as enum (
    'Screen', 'Battery', 'Charging Port', 'Speaker / Mic',
    'Camera', 'Back Glass', 'Board / IC', 'Other'
  );
exception when duplicate_object then null; end $$;

do $$ begin
  create type part_request_status as enum ('Pending', 'Approved', 'Issued', 'Rejected');
exception when duplicate_object then null; end $$;

-- ── The catalogue ───────────────────────────────────────────────────────────

create table if not exists public.repair_parts (
  id              bigint generated by default as identity primary key,
  -- Unique because request rows point at parts by SKU, and because two rows
  -- sharing one SKU would make "how many do we have" unanswerable.
  sku             text not null unique,
  name            text not null,
  category        part_category not null default 'Other',
  compatible_with text[] not null default '{}',
  stock           integer not null default 0 check (stock >= 0),
  reorder_level   integer not null default 0 check (reorder_level >= 0),
  cost_price      numeric(12,2) not null default 0 check (cost_price >= 0),
  location        text not null default '',
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now(),
  created_by      uuid references auth.users (id) on delete set null
);

create index if not exists repair_parts_category_idx on public.repair_parts (category);

drop trigger if exists trg_repair_parts_touch on public.repair_parts;
create trigger trg_repair_parts_touch
  before update on public.repair_parts
  for each row execute function public.touch_updated_at();

-- ── Requests against it ─────────────────────────────────────────────────────

create table if not exists public.repair_part_requests (
  id              bigint generated by default as identity primary key,
  job_id          text not null references public.repair_jobs (id) on delete cascade,
  -- job_device and part_name are denormalised on purpose: the request list has
  -- to stay readable after a part is delisted, so the names are copied rather
  -- than joined. part_sku is the live link and goes null if the part is gone.
  job_device      text not null default '',
  technician_name text not null,
  part_sku        text references public.repair_parts (sku) on update cascade on delete set null,
  part_name       text not null,
  quantity        integer not null default 1 check (quantity > 0),
  status          part_request_status not null default 'Pending',
  note            text,
  requested_at    timestamptz not null default now(),
  resolved_at     timestamptz,
  installed_at    timestamptz,
  requested_by    uuid references auth.users (id) on delete set null,
  resolved_by     uuid references auth.users (id) on delete set null
);

create index if not exists repair_part_requests_job_idx    on public.repair_part_requests (job_id);
create index if not exists repair_part_requests_status_idx on public.repair_part_requests (status);

-- ── Resolving a request ─────────────────────────────────────────────────────
-- In Postgres rather than in the browser because approving deducts stock, and
-- the client version could not do the two together safely: two admins
-- approving at the same moment both read stock 5, both wrote 4, and one screen
-- went missing from the count. The row lock plus the `stock >= quantity` guard
-- make the read-modify-write one atomic step, so the second attempt fails
-- loudly instead of overselling.

create or replace function public.resolve_part_request(
  p_request_id bigint,
  p_status     part_request_status
) returns public.repair_part_requests
language plpgsql
security definer
set search_path = public
as $$
declare
  req public.repair_part_requests;
begin
  -- SECURITY DEFINER bypasses RLS, so the role check has to be explicit.
  if not public.is_staff() then
    raise exception 'Not authorised to resolve part requests';
  end if;

  if p_status not in ('Approved', 'Rejected') then
    raise exception 'resolve_part_request expects Approved or Rejected, got %', p_status;
  end if;

  select * into req
    from public.repair_part_requests
   where id = p_request_id
     for update;

  if not found then
    raise exception 'Part request % not found', p_request_id;
  end if;

  -- Idempotent: a double-click, or two admins racing, returns the settled row
  -- rather than deducting stock a second time.
  if req.status <> 'Pending' then
    return req;
  end if;

  if p_status = 'Approved' then
    if req.part_sku is null then
      raise exception 'That part is no longer in the catalogue, so stock cannot be deducted';
    end if;

    update public.repair_parts
       set stock = stock - req.quantity
     where sku = req.part_sku
       and stock >= req.quantity;

    if not found then
      raise exception 'Not enough % in stock to approve % unit(s)', req.part_sku, req.quantity;
    end if;
  end if;

  update public.repair_part_requests
     set status      = p_status,
         resolved_at = now(),
         resolved_by = auth.uid()
   where id = p_request_id
  returning * into req;

  return req;
end $$;

-- ── Creating a request ──────────────────────────────────────────────────────
-- Auto-approval (the "use parts without approval" permission) has to deduct
-- stock in the same transaction that creates the request, or a technician can
-- be told "approved" for a part that just ran out.

create or replace function public.create_part_request(
  p_job_id          text,
  p_job_device      text,
  p_technician_name text,
  p_part_sku        text,
  p_part_name       text,
  p_quantity        integer,
  p_note            text,
  p_auto_approve    boolean
) returns public.repair_part_requests
language plpgsql
security definer
set search_path = public
as $$
declare
  req public.repair_part_requests;
begin
  if not public.is_staff() then
    raise exception 'Not authorised to request parts';
  end if;

  insert into public.repair_part_requests
    (job_id, job_device, technician_name, part_sku, part_name, quantity, note, requested_by)
  values
    (p_job_id, p_job_device, p_technician_name, p_part_sku, p_part_name,
     p_quantity, nullif(p_note, ''), auth.uid())
  returning * into req;

  if p_auto_approve then
    req := public.resolve_part_request(req.id, 'Approved'::part_request_status);
  end if;

  return req;
end $$;

-- ── Row level security ──────────────────────────────────────────────────────

alter table public.repair_parts         enable row level security;
alter table public.repair_part_requests enable row level security;

-- Everyone on staff needs to read the catalogue: technicians pick from it when
-- requesting, cashiers see part costs against a job.
drop policy if exists parts_catalog_select on public.repair_parts;
create policy parts_catalog_select on public.repair_parts
  for select to authenticated using (public.is_staff());

-- Managed from Admin Control, which is reached through the cashier route.
drop policy if exists parts_catalog_write on public.repair_parts;
create policy parts_catalog_write on public.repair_parts
  for all to authenticated
  using (public.has_role('Admin'::staff_role, 'Cashier'::staff_role))
  with check (public.has_role('Admin'::staff_role, 'Cashier'::staff_role));

drop policy if exists part_requests_select on public.repair_part_requests;
create policy part_requests_select on public.repair_part_requests
  for select to authenticated using (public.is_staff());

-- Technicians raise requests and mark them installed; admins/cashiers resolve.
-- The stock-changing path goes through the definer functions above, so this
-- only has to cover ordinary inserts and the installed_at stamp.
drop policy if exists part_requests_write on public.repair_part_requests;
create policy part_requests_write on public.repair_part_requests
  for all to authenticated
  using (public.has_role('Admin'::staff_role, 'Cashier'::staff_role, 'Technician'::staff_role))
  with check (public.has_role('Admin'::staff_role, 'Cashier'::staff_role, 'Technician'::staff_role));

comment on table public.repair_parts is
  'Spare parts the shop stocks for repairs. Separate from retail inventory; see repair_parts_used for what was consumed on a job.';
comment on table public.repair_part_requests is
  'A technician asking for stock off repair_parts, and the admin decision on it. Approving deducts stock via resolve_part_request().';
