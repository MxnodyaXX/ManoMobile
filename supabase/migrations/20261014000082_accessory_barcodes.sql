-- ============================================================================
-- Mano Mobile — manufacturer barcodes on accessories
--
-- Most accessory boxes already carry an EAN-13 / UPC barcode. Linking that
-- code to the product once means the counter can scan the box itself, and
-- the shop only prints its own label for loose items with no packaging.
--
-- A separate table rather than a `barcode` column on accessory_products,
-- because the link is many-to-many in practice:
--   * one product, several barcodes — the same charger bought from two
--     suppliers arrives in two differently coded boxes;
--   * one barcode, several products — unbranded cases and cables often reuse
--     one barcode across every colour/model. The sales screen asks the
--     cashier which one when a scan matches more than one product.
-- So the only uniqueness is (product, barcode): the same code twice on one
-- product is a duplicate, the same code on two products is allowed.
--
-- The product's own `code` (what the shop's printed label encodes) still
-- scans as before — this table only adds the manufacturer codes alongside it.
-- ============================================================================

create table if not exists public.accessory_barcodes (
  id         bigint generated by default as identity primary key,
  product_id bigint not null references public.accessory_products (id) on delete cascade,
  barcode    text not null check (length(btrim(barcode)) > 0),
  created_at timestamptz not null default now(),
  created_by uuid references auth.users (id) on delete set null default auth.uid()
);

create unique index if not exists accessory_barcodes_product_barcode_key
  on public.accessory_barcodes (product_id, barcode);
create index if not exists accessory_barcodes_barcode_idx
  on public.accessory_barcodes (barcode);

comment on table public.accessory_barcodes is
  'Manufacturer barcodes (EAN/UPC off the packaging) linked to accessory_products. Many-to-many on purpose: one product can have several, and cheap accessories often share one barcode across products.';

-- ── Replacing a product's barcode list in one go ────────────────────────────
-- The Add/Edit Product form edits the whole list at once. Doing the delete
-- and the inserts as separate client calls could leave a product with half
-- its barcodes if the second call failed, so it is one function, one
-- transaction. Security invoker: RLS below decides who may write.
create or replace function public.set_accessory_barcodes(p_product_id bigint, p_barcodes text[])
returns void
language plpgsql
security invoker
set search_path = public
as $$
begin
  delete from public.accessory_barcodes
   where product_id = p_product_id
     and barcode <> all (
       select btrim(b) from unnest(coalesce(p_barcodes, '{}')) as b
     );

  insert into public.accessory_barcodes (product_id, barcode)
  select distinct p_product_id, btrim(b)
    from unnest(coalesce(p_barcodes, '{}')) as b
   where length(btrim(b)) > 0
  on conflict (product_id, barcode) do nothing;
end $$;

comment on function public.set_accessory_barcodes(bigint, text[]) is
  'Replaces the full set of manufacturer barcodes on one accessory product, atomically. Blank entries are ignored and surrounding whitespace trimmed.';

-- ── Row Level Security — same split as accessory_products ───────────────────

alter table public.accessory_barcodes enable row level security;

drop policy if exists accessory_barcodes_select on public.accessory_barcodes;
create policy accessory_barcodes_select on public.accessory_barcodes
  for select to authenticated using (public.is_staff());
drop policy if exists accessory_barcodes_write on public.accessory_barcodes;
create policy accessory_barcodes_write on public.accessory_barcodes
  for all to authenticated
  using (public.has_role('Admin'::staff_role, 'Cashier'::staff_role))
  with check (public.has_role('Admin'::staff_role, 'Cashier'::staff_role));

-- ── Realtime — a barcode linked at one till should scan at the other ───────

do $$
begin
  if not exists (
    select 1 from pg_publication_tables
     where pubname = 'supabase_realtime'
       and schemaname = 'public'
       and tablename = 'accessory_barcodes'
  ) then
    alter publication supabase_realtime add table public.accessory_barcodes;
  end if;
end $$;
