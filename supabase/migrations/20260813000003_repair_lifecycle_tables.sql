-- Agents: all staff read (technicians pick one when transferring), Admin maintains.
drop policy if exists agents_select on public.repair_agents;
create policy agents_select on public.repair_agents
  for select to authenticated using (public.is_staff());

drop policy if exists agents_admin_write on public.repair_agents;
create policy agents_admin_write on public.repair_agents
  for all to authenticated
  using (public.has_role('Admin'::staff_role)) with check (public.has_role('Admin'::staff_role));

-- Technician-side records: staff read; technicians and above write.
drop policy if exists assignments_select on public.repair_assignments;
create policy assignments_select on public.repair_assignments
  for select to authenticated using (public.is_staff());

drop policy if exists assignments_write on public.repair_assignments;
create policy assignments_write on public.repair_assignments
  for all to authenticated
