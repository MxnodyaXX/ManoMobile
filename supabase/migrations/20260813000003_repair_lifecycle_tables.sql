-- ============================================================================
-- Mano Mobile — repair lifecycle tables
--
-- The repair now has a table per stage, as specified:
--
--   repair_jobs           the new repair as taken in at the counter
--     └─ repair_assignments   the technician side: assigned or self-taken,
--        └─ repair_parts_used  started/finished stamps, parts, work notes
--     └─ repair_non_issued    finished repairing, waiting for collection
--        └─ repair_issued     collected by the customer
--     └─ repair_agent_transfers  sent out to an external repair agent
--   repair_agents         the external agents themselves (admin-managed)
--
-- HOW THE STAGES ARE FILLED
-- Each stage table is keyed by job_id and holds the facts belonging to THAT
-- stage; it does not re-copy the customer/device columns. Copying every field
-- forward would mean the same repair existing four times, with no way to tell
-- which copy is right once someone corrects a phone number. The views at the
-- bottom (v_new_repairs, v_technician_jobs, v_non_issued, v_issued) join the
-- stage back to the job, so querying a stage still returns the whole repair.
--
-- The triggers below fill the stage tables automatically as a job moves, so a
-- stage can never be silently skipped by app code that forgot to write it.
-- ============================================================================

-- ── Enums ───────────────────────────────────────────────────────────────────

do $$ begin
  -- How the technician came to own the job. Both live in one column, as asked.
  create type assignment_type as enum ('Assigned', 'Self-Taken');
exception when duplicate_object then null; end $$;

do $$ begin
  create type agent_transfer_status as enum ('Sent', 'Returned', 'Cancelled');
exception when duplicate_object then null; end $$;

-- ── How the job was taken on ────────────────────────────────────────────────
-- Set by the app: intake/cashier assignment writes 'Assigned', a technician
-- claiming an unassigned job writes 'Self-Taken'. Without it the trigger could
-- only guess, and a cashier assigning a job late would look like a self-claim.

alter table public.repair_jobs
  add column if not exists assignment_source assignment_type;

comment on column public.repair_jobs.assignment_source is
  'How the current technician got the job. Copied into repair_assignments by trigger.';

-- ── External repair agents (managed by Admin) ───────────────────────────────

create table if not exists public.repair_agents (
  id          bigint generated by default as identity primary key,
  name        text not null,
  contact     text not null default '',
  address     text not null default '',
  speciality  text,
  active      boolean not null default true,
  joined_at   date not null default current_date,
  remarks     text,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  created_by  uuid references auth.users (id) on delete set null
);

create unique index if not exists repair_agents_name_key
  on public.repair_agents (lower(name));

drop trigger if exists trg_repair_agents_touch on public.repair_agents;
create trigger trg_repair_agents_touch
  before update on public.repair_agents
  for each row execute function public.touch_updated_at();

-- ── Technician side ─────────────────────────────────────────────────────────
-- One row per job: who owns it, how they got it, and every technician-side
-- detail. Reassignment overwrites the row; the full history of who held it is
-- in repair_job_events.

create table if not exists public.repair_assignments (
  job_id           text primary key references public.repair_jobs (id) on delete cascade,

  technician_name  text not null,
  technician_id    uuid references public.profiles (id) on delete set null,
  assignment_type  assignment_type not null,

  assigned_at      timestamptz not null default now(),
  started_at       timestamptz,
  paused_at        timestamptz,
  resumed_at       timestamptz,
  finished_at      timestamptz,

  -- Technician's own record of the work
  work_summary     text,
  tech_remarks     text,
  future_faults    text,
  diagnostic_notes text,
  internal_notes   text,

  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);

comment on column public.repair_assignments.assignment_type is
  'Assigned = given to this technician at intake or by staff. Self-Taken = the technician picked up an unassigned job themselves.';

create index if not exists repair_assignments_tech_idx
  on public.repair_assignments (technician_name);
create index if not exists repair_assignments_tech_id_idx
  on public.repair_assignments (technician_id);

drop trigger if exists trg_repair_assignments_touch on public.repair_assignments;
create trigger trg_repair_assignments_touch
  before update on public.repair_assignments
  for each row execute function public.touch_updated_at();

-- ── Parts consumed ──────────────────────────────────────────────────────────
-- A table rather than a text[] so parts can be costed and counted across jobs.

create table if not exists public.repair_parts_used (
  id         bigint generated by default as identity primary key,
  job_id     text not null references public.repair_jobs (id) on delete cascade,
  part_name  text not null,
  part_sku   text,
  quantity   integer not null default 1 check (quantity > 0),
  unit_cost  numeric(12,2) not null default 0 check (unit_cost >= 0),
  added_by   uuid references auth.users (id) on delete set null,
  added_at   timestamptz not null default now()
);

create index if not exists repair_parts_used_job_idx
  on public.repair_parts_used (job_id);

-- ── Finished repairing, not yet collected ───────────────────────────────────

create table if not exists public.repair_non_issued (
  job_id        text primary key references public.repair_jobs (id) on delete cascade,
  finished_at   timestamptz not null default now(),
  finished_by   text,
  ready_notes   text,
  -- Filled in the moment the customer collects; also mirrored into repair_issued.
  collected_at  timestamptz,
  created_at    timestamptz not null default now()
);

comment on column public.repair_non_issued.collected_at is
  'Date/time the customer collected. Null while the device is still on the shelf.';

create index if not exists repair_non_issued_waiting_idx
  on public.repair_non_issued (finished_at) where collected_at is null;

-- ── Collected by the customer ───────────────────────────────────────────────

create table if not exists public.repair_issued (
  job_id             text primary key references public.repair_jobs (id) on delete cascade,
  collected_at       timestamptz not null default now(),
  collected_by       text,
  relationship       text,
  id_verified        boolean not null default false,
  balance_settled    numeric(12,2) not null default 0,
  payment_method     text,
  handover_signature text,
  handed_over_by     text,
  created_at         timestamptz not null default now()
);

-- ── Sent to an external agent ───────────────────────────────────────────────
-- Raised from the technician side; the agents themselves are admin-managed.

create table if not exists public.repair_agent_transfers (
  id              bigint generated by default as identity primary key,
  job_id          text not null references public.repair_jobs (id) on delete cascade,
  agent_id        bigint not null references public.repair_agents (id) on delete restrict,
  status          agent_transfer_status not null default 'Sent',
  reason          text,
  expected_return date,
  agreed_cost     numeric(12,2),
  sent_at         timestamptz not null default now(),
  sent_by         text,
  returned_at     timestamptz,
  return_notes    text,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);

create index if not exists repair_agent_transfers_job_idx   on public.repair_agent_transfers (job_id);
create index if not exists repair_agent_transfers_agent_idx on public.repair_agent_transfers (agent_id);
-- A job can only be out at one agent at a time.
create unique index if not exists repair_agent_transfers_one_open
  on public.repair_agent_transfers (job_id) where status = 'Sent';

drop trigger if exists trg_repair_agent_transfers_touch on public.repair_agent_transfers;
create trigger trg_repair_agent_transfers_touch
  before update on public.repair_agent_transfers
  for each row execute function public.touch_updated_at();

-- ============================================================================
-- Lifecycle triggers — the stage tables fill themselves
-- ============================================================================

create or replace function public.sync_repair_stages()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_tech_id     uuid;
  v_type        assignment_type;
  -- OLD is unassigned inside an INSERT trigger and touching it raises
  -- "record old is not assigned yet", so read it once, only on UPDATE, and
  -- work from these locals below.
  v_old_status  job_status := null;
  v_old_tech    text       := null;
  v_old_started timestamptz := null;
  v_old_paused  timestamptz := null;
begin
  if tg_op = 'UPDATE' then
    v_old_status  := old.status;
    v_old_tech    := old.technician;
    v_old_started := old.started_at;
    v_old_paused  := old.paused_at;
  end if;

  -- ── Technician stage ──
  -- Fires when a job arrives already assigned, or when it gains/changes a
  -- technician later (assignment by staff, or a technician claiming it).
  if new.technician is not null
     and new.technician <> 'Unassigned'
     and (tg_op = 'INSERT' or new.technician is distinct from v_old_tech)
  then
    select id into v_tech_id
      from public.profiles
     where role = 'Technician' and lower(full_name) = lower(new.technician)
     limit 1;

    v_type := coalesce(
      new.assignment_source,
      -- Fallback when the app did not say: a job moving off 'Unassigned' was
      -- picked up by the technician; anything else was handed to them.
      case when v_old_tech = 'Unassigned'
           then 'Self-Taken'::assignment_type
           else 'Assigned'::assignment_type end
    );

    insert into public.repair_assignments (
      job_id, technician_name, technician_id, assignment_type, assigned_at, started_at
    )
    values (new.id, new.technician, v_tech_id, v_type, now(), new.started_at)
    on conflict (job_id) do update
      set technician_name = excluded.technician_name,
          technician_id   = excluded.technician_id,
          assignment_type = excluded.assignment_type,
          assigned_at     = now(),
          -- Keep the original start stamp if the job was already under way.
          -- (Unqualified table name — a schema-qualified one is not valid here.)
          started_at      = coalesce(repair_assignments.started_at, excluded.started_at);
  end if;

  -- Work timestamps follow the job's own stamps.
  if tg_op = 'UPDATE' then
    if new.started_at is distinct from v_old_started and new.started_at is not null then
      update public.repair_assignments
         set started_at = coalesce(started_at, new.started_at)
       where job_id = new.id;
    end if;
    if new.paused_at is distinct from v_old_paused then
      update public.repair_assignments set paused_at = new.paused_at where job_id = new.id;
    end if;
    if new.status = 'Issued' and v_old_status = 'Pending' then
      update public.repair_assignments set resumed_at = now() where job_id = new.id;
    end if;
  end if;

  -- ── Finished repairing → non-issued (waiting for collection) ──
  if new.status = 'Completed' and v_old_status is distinct from 'Completed' then
    update public.repair_assignments
       set finished_at   = coalesce(finished_at, coalesce(new.completed_at, now())),
           tech_remarks  = coalesce(new.tech_remarks, tech_remarks),
           future_faults = coalesce(new.future_faults, future_faults)
     where job_id = new.id;

    insert into public.repair_non_issued (job_id, finished_at, finished_by, ready_notes)
    values (new.id, coalesce(new.completed_at, now()), new.technician, new.tech_remarks)
    on conflict (job_id) do update
      set finished_at = excluded.finished_at,
          finished_by = excluded.finished_by;
  end if;

  -- ── Collected → issued (and stamp the non-issued row) ──
  if new.status = 'Delivered' and v_old_status is distinct from 'Delivered' then
    update public.repair_non_issued
       set collected_at = coalesce(collected_at, now())
     where job_id = new.id;

    insert into public.repair_issued (
      job_id, collected_at, collected_by, relationship, id_verified,
      balance_settled, payment_method, handover_signature, handed_over_by
    )
    values (
      new.id,
      coalesce((new.handover ->> 'handedOverAt')::timestamptz, now()),
      new.handover ->> 'collectedBy',
      new.handover ->> 'relationship',
      coalesce((new.handover ->> 'idVerified')::boolean, false),
      coalesce((new.handover ->> 'balanceSettled')::numeric, 0),
      new.handover ->> 'paymentMethod',
      new.handover ->> 'handoverSignature',
      new.handover ->> 'handedOverBy'
    )
    on conflict (job_id) do nothing;   -- collection happens once
  end if;

  return new;
end $$;

drop trigger if exists trg_repair_jobs_sync_stages on public.repair_jobs;
create trigger trg_repair_jobs_sync_stages
  after insert or update on public.repair_jobs
  for each row execute function public.sync_repair_stages();

-- ── Backfill ────────────────────────────────────────────────────────────────
-- Populate the stages from jobs that already exist, so the new tables are not
-- empty for work taken in before this migration. Written as plain inserts
-- rather than by re-saving each job: touching the primary key to re-fire the
-- trigger would ripple through every foreign key that references it.

insert into public.repair_assignments (
  job_id, technician_name, technician_id, assignment_type, assigned_at, started_at, finished_at, tech_remarks, future_faults
)
select j.id, j.technician,
       (select p.id from public.profiles p
         where p.role = 'Technician' and lower(p.full_name) = lower(j.technician) limit 1),
       coalesce(j.assignment_source, 'Assigned'::assignment_type),
       j.created_at, j.started_at, j.completed_at, j.tech_remarks, j.future_faults
  from public.repair_jobs j
 where coalesce(j.technician, 'Unassigned') <> 'Unassigned'
on conflict (job_id) do nothing;

insert into public.repair_non_issued (job_id, finished_at, finished_by, ready_notes, collected_at)
select j.id, coalesce(j.completed_at, j.updated_at), j.technician, j.tech_remarks,
       case when j.status = 'Delivered'
            then coalesce((j.handover ->> 'handedOverAt')::timestamptz, j.updated_at) end
  from public.repair_jobs j
 where j.status in ('Completed', 'Delivered')
on conflict (job_id) do nothing;

insert into public.repair_issued (
  job_id, collected_at, collected_by, relationship, id_verified, balance_settled,
  payment_method, handover_signature, handed_over_by
)
select j.id,
       coalesce((j.handover ->> 'handedOverAt')::timestamptz, j.updated_at),
       j.handover ->> 'collectedBy',
       j.handover ->> 'relationship',
       coalesce((j.handover ->> 'idVerified')::boolean, false),
       coalesce((j.handover ->> 'balanceSettled')::numeric, 0),
       j.handover ->> 'paymentMethod',
       j.handover ->> 'handoverSignature',
       j.handover ->> 'handedOverBy'
  from public.repair_jobs j
 where j.status = 'Delivered'
on conflict (job_id) do nothing;

-- Parts recorded on the old text[] column become proper rows.
insert into public.repair_parts_used (job_id, part_name, quantity)
select j.id, part, 1
  from public.repair_jobs j
  cross join lateral unnest(j.parts_used) as part
 where array_length(j.parts_used, 1) > 0;

-- ============================================================================
-- Views — a stage, with the whole repair attached
-- ============================================================================

create or replace view public.v_new_repairs as
  select j.*, (a.job_id is null) as awaiting_technician
    from public.repair_jobs j
    left join public.repair_assignments a on a.job_id = j.id
   where j.status not in ('Cancelled');

create or replace view public.v_technician_jobs as
  select a.*, j.customer_name, j.phone, j.brand, j.model, j.imei, j.issue,
         j.priority, j.status, j.estimated_cost, j.advance_paid,
         j.estimated_completion, j.created_at as job_created_at,
         (select coalesce(sum(p.unit_cost * p.quantity), 0)
            from public.repair_parts_used p where p.job_id = a.job_id) as parts_cost
    from public.repair_assignments a
    join public.repair_jobs j on j.id = a.job_id;

create or replace view public.v_non_issued as
  select n.*, j.customer_name, j.phone, j.brand, j.model, j.imei, j.issue,
         j.estimated_cost, j.advance_paid,
         (j.estimated_cost - j.advance_paid) as balance_due,
         a.technician_name
    from public.repair_non_issued n
    join public.repair_jobs j on j.id = n.job_id
    left join public.repair_assignments a on a.job_id = n.job_id
   where n.collected_at is null;

create or replace view public.v_issued as
  select i.*, j.customer_name, j.phone, j.brand, j.model, j.imei, j.issue,
         j.estimated_cost, j.advance_paid, a.technician_name
    from public.repair_issued i
    join public.repair_jobs j on j.id = i.job_id
    left join public.repair_assignments a on a.job_id = i.job_id;

