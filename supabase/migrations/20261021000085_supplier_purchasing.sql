create or replace function public.tg_accessory_batch_status()
returns trigger
language plpgsql
as $$
begin
  if new.status <> 'Reversed' then
    new.status := case when new.qty_available = 0 then 'Depleted' else 'Active' end;
  end if;
  return new;
end $$;

