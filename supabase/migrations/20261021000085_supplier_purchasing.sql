create index if not exists purchase_invoices_supplier_idx on public.purchase_invoices (supplier_id, invoice_date desc);

drop trigger if exists trg_purchase_invoices_touch on public.purchase_invoices;
create trigger trg_purchase_invoices_touch
  before update on public.purchase_invoices
  for each row execute function public.touch_updated_at();

create table if not exists public.purchase_invoice_items (
  id                      bigint generated by default as identity primary key,
  invoice_id              bigint not null references public.purchase_invoices (id) on delete cascade,
  -- Restrict: a product that was bought on an invoice can't be deleted out
  -- from under its purchase history.
  product_id              bigint references public.accessory_products (id) on delete restrict,
  -- {name, code, category, subcategory, brand, model, description, barcodes[], min_stock}
  -- for a product not in the catalogue yet; created at finalise.
  new_product             jsonb,
  description             text not null default '',
  qty                     integer not null check (qty > 0),
  received_qty            integer not null default 0 check (received_qty >= 0 and received_qty <= qty),
  unit_cost               numeric(12,2) not null check (unit_cost >= 0),
  expected_sell_price     numeric(12,2) not null default 0 check (expected_sell_price >= 0),
  discount                numeric(12,2) not null default 0 check (discount >= 0),
  tax_pct                 numeric(5,2) not null default 0 check (tax_pct >= 0 and tax_pct <= 100),
  line_total              numeric(12,2) not null default 0,
  -- Never overwrite a product's selling price silently: only when asked.
  update_selling_price    boolean not null default false,
  supplier_warranty_days  integer check (supplier_warranty_days is null or supplier_warranty_days >= 0),
  supplier_warranty_start text not null default 'invoice_date'
