  supplier_warranty_notes text not null default '',
  supplier_warranty_terms text not null default '',
  -- What the shop gives its own customer — separate on purpose. Null = the
  -- shop's warranty policy applies at the counter.
  customer_warranty_days  integer check (customer_warranty_days is null or customer_warranty_days >= 0),
  sort_order              integer not null default 0,
  check (product_id is not null or new_product is not null)
);
