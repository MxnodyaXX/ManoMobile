-- ── Who may buy stock ───────────────────────────────────────────────────────
-- Same people who may edit the accessory catalogue.
create or replace function public._purchasing_guard()
returns void
language plpgsql
stable
set search_path = public
as $$
begin
  if not public.has_role('Admin'::staff_role, 'Cashier'::staff_role) then
    raise exception 'Not authorised to record supplier purchases';
  end if;
end $$;

-- ── Purchase invoices ───────────────────────────────────────────────────────

create table if not exists public.purchase_invoices (
  id              bigint generated by default as identity primary key,
  -- Our own reference, so an invoice can be named before the supplier's
  -- number is even typed in.
  ref             text not null unique default ('PI-' || lpad(nextval('public.purchase_invoice_ref_seq')::text, 6, '0')),
  supplier_id     bigint not null references public.accessory_suppliers (id) on delete restrict,
  supplier_name   text not null default '',
  invoice_no      text not null check (length(btrim(invoice_no)) > 0),
  invoice_date    date not null default current_date,
  due_date        date,
  status          text not null default 'Draft' check (status in ('Draft', 'Open', 'Void')),
  items_subtotal  numeric(12,2) not null default 0,
  expenses        numeric(12,2) not null default 0 check (expenses >= 0),
  discount        numeric(12,2) not null default 0 check (discount >= 0),
  total           numeric(12,2) not null default 0 check (total >= 0),
  notes           text not null default '',
  attachment_path text,
  attachment_name text,
  -- A payment typed on the form while the invoice is still a draft. Recorded
  -- as a real supplier_payments row when the invoice is finalised — a draft's
  -- total can still change, so it cannot carry a payment yet.
  initial_payment jsonb,
  created_by      uuid default auth.uid() references auth.users (id) on delete set null,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now(),
  finalised_at    timestamptz,
  finalised_by    uuid references auth.users (id) on delete set null,
  voided_at       timestamptz,
  voided_by       uuid references auth.users (id) on delete set null,
  void_reason     text
);

