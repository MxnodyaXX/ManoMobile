-- ── Finalise: create new products, lock the bill, record the first payment ──

create or replace function public.finalise_purchase_invoice(p_id bigint, p_receive_all boolean default false)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_inv  public.purchase_invoices;
  v_it   record;
  v_np   jsonb;
  v_code text;
  v_new  bigint;
  v_b    text;
  v_pay  jsonb;
begin
  perform public._purchasing_guard();
  select * into v_inv from public.purchase_invoices where id = p_id for update;
  if not found then raise exception 'Purchase invoice % not found', p_id; end if;
  if v_inv.status <> 'Draft' then raise exception 'This invoice is already %', v_inv.status; end if;

  for v_it in
    select * from public.purchase_invoice_items where invoice_id = p_id and product_id is null order by sort_order for update
  loop
    v_np   := v_it.new_product;
    v_code := btrim(coalesce(v_np ->> 'code', ''));
    if v_code = '' then
      raise exception 'New product "%" needs an item code', v_np ->> 'name';
    end if;
    if exists (select 1 from public.accessory_products where lower(code) = lower(v_code)) then
      raise exception 'Item code % is already used — select that product instead of creating a new one', v_code;
    end if;
    if exists (
      select 1 from public.accessory_products
       where lower(btrim(name)) = lower(btrim(v_np ->> 'name'))
         and lower(btrim(brand)) = lower(btrim(coalesce(v_np ->> 'brand', '')))
         and lower(btrim(model)) = lower(btrim(coalesce(v_np ->> 'model', '')))
    ) then
      raise exception '"%" already exists in the catalogue — select it so this delivery becomes a new batch of it', v_np ->> 'name';
    end if;

    insert into public.accessory_products (
      code, name, brand, category, subcategory, model, description,
      buying_price, selling_price, stock, min_stock, supplier, created_by
    ) values (
      v_code, btrim(v_np ->> 'name'), coalesce(v_np ->> 'brand', ''), coalesce(v_np ->> 'category', ''),
      coalesce(v_np ->> 'subcategory', ''), coalesce(v_np ->> 'model', ''), coalesce(v_np ->> 'description', ''),
      round(v_it.line_total / v_it.qty, 2), v_it.expected_sell_price, 0,
      coalesce(nullif(v_np ->> 'min_stock', '')::integer, 5), v_inv.supplier_name, auth.uid()
    ) returning id into v_new;

    for v_b in select btrim(x) from jsonb_array_elements_text(coalesce(v_np -> 'barcodes', '[]'::jsonb)) x loop
      if v_b <> '' then
        insert into public.accessory_barcodes (product_id, barcode) values (v_new, v_b)
        on conflict (product_id, barcode) do nothing;
      end if;
    end loop;

    update public.purchase_invoice_items set product_id = v_new, update_selling_price = false where id = v_it.id;
    perform public._purchase_event(p_id, 'product_created', btrim(v_np ->> 'name') || ' (' || v_code || ') added to the catalogue');
  end loop;

  update public.purchase_invoices
     set status = 'Open', finalised_at = now(), finalised_by = auth.uid()
   where id = p_id;
  perform public._purchase_event(p_id, 'finalised', 'Invoice finalised — Rs ' || v_inv.total);

  v_pay := v_inv.initial_payment;
  if v_pay is not null and coalesce(nullif(v_pay ->> 'amount', '')::numeric, 0) > 0 then
    perform public.record_supplier_payment(
      v_inv.supplier_id,
      coalesce(nullif(v_pay ->> 'paid_on', '')::date, current_date),
      coalesce(nullif(v_pay ->> 'method', ''), 'Cash'),
      coalesce(v_pay ->> 'reference', ''),
      coalesce(v_pay ->> 'notes', ''),
      jsonb_build_array(jsonb_build_object('invoice_id', p_id, 'amount', (v_pay ->> 'amount')::numeric))
    );
    update public.purchase_invoices set initial_payment = null where id = p_id;
  end if;

  if p_receive_all then
    perform public.receive_purchase_invoice(p_id, null, current_date, 'Received with the invoice');
  end if;
end $$;

-- ── Void (or delete a draft) ────────────────────────────────────────────────
-- A finalised invoice is never edited: it is voided — stock it brought in is
-- taken back out, its batches marked Reversed — and entered again. Only
-- allowed while none of its stock has been sold and none of it is paid.
create or replace function public.void_purchase_invoice(p_id bigint, p_reason text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_inv public.purchase_invoices;
  v_b   record;
begin
  perform public._purchasing_guard();
  select * into v_inv from public.purchase_invoices where id = p_id for update;
  if not found then raise exception 'Purchase invoice % not found', p_id; end if;

  if v_inv.status = 'Draft' then
    delete from public.purchase_invoices where id = p_id;
    return;
  end if;
  if v_inv.status = 'Void' then return; end if;
  if coalesce(btrim(p_reason), '') = '' then raise exception 'Give a reason for voiding the invoice'; end if;

  if exists (
    select 1 from public.supplier_payment_allocations a
      join public.supplier_payments sp on sp.id = a.payment_id and sp.status = 'Valid'
     where a.invoice_id = p_id
  ) then
    raise exception 'This invoice has payments against it — void those payments first';
  end if;

  for v_b in
    select b.*, p.name as product_name from public.accessory_batches b
      join public.accessory_products p on p.id = b.product_id
     where b.invoice_id = p_id and b.status <> 'Reversed'
  loop
    if v_b.qty_available < v_b.qty_received then
      raise exception '% from batch % has already gone out (% of %) — it can''t be reversed. Adjust the stock instead.',
        v_b.product_name, v_b.batch_no, v_b.qty_received - v_b.qty_available, v_b.qty_received;
    end if;
  end loop;

  perform set_config('mm.stock_source', 'managed', true);
  for v_b in select * from public.accessory_batches where invoice_id = p_id and status <> 'Reversed' for update loop
    update public.accessory_products set stock = stock - v_b.qty_received where id = v_b.product_id and stock >= v_b.qty_received;
    if not found then
      raise exception 'Stock of product % is lower than batch % — adjust the stock first', v_b.product_id, v_b.batch_no;
    end if;
    update public.accessory_batches set qty_available = 0, status = 'Reversed' where id = v_b.id;
    insert into public.accessory_stock_movements (product_id, batch_id, kind, qty, unit_cost, purchase_invoice_id, note)
    values (v_b.product_id, v_b.id, 'reversal', -v_b.qty_received, v_b.unit_cost, p_id, 'Invoice voided: ' || p_reason);
  end loop;
  perform set_config('mm.stock_source', '', true);

  update public.purchase_invoices
     set status = 'Void', voided_at = now(), voided_by = auth.uid(), void_reason = p_reason
   where id = p_id;
  perform public._purchase_event(p_id, 'voided', p_reason);
end $$;

-- ── Keeping batches in step with every other stock change ───────────────────

create or replace function public.tg_accessory_stock_batches()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_delta     integer;
  v_remaining integer;
  v_take      integer;
  v_b         record;
  v_inv       text := nullif(current_setting('mm.voiding_invoice', true), '');
  v_reason    text := nullif(current_setting('mm.stock_reason', true), '');
  v_key       uuid := nullif(current_setting('mm.sale_key', true), '')::uuid;
  v_batch     bigint;
begin
  if coalesce(current_setting('mm.stock_source', true), '') = 'managed' then
    return new;
  end if;

  v_delta := new.stock - case when tg_op = 'INSERT' then 0 else old.stock end;
  if v_delta = 0 then return new; end if;

  if v_delta > 0 then
    v_remaining := v_delta;
    -- A voided sale: back into the batches it was taken from, newest first.
    if v_inv is not null then
      for v_b in
        select m.batch_id, -sum(m.qty)::integer as out_qty
          from public.accessory_stock_movements m
         where m.product_id = new.id and m.invoice_no = v_inv
           and m.kind in ('sale', 'void_return') and m.batch_id is not null
         group by m.batch_id
        having -sum(m.qty) > 0
         order by m.batch_id desc
      loop
        exit when v_remaining <= 0;
        v_take := least(v_remaining, v_b.out_qty);
        update public.accessory_batches
           set qty_available = least(qty_received, qty_available + v_take)
         where id = v_b.batch_id and status <> 'Reversed';
        if found then
          insert into public.accessory_stock_movements (product_id, batch_id, kind, qty, unit_cost, invoice_no, note)
          select new.id, v_b.batch_id, 'void_return', v_take, unit_cost, v_inv, 'Sale voided'
            from public.accessory_batches where id = v_b.batch_id;
          v_remaining := v_remaining - v_take;
        end if;
      end loop;
    end if;

    if v_remaining > 0 then
      insert into public.accessory_batches (product_id, source, supplier_name, received_on, qty_received, qty_available, unit_cost)
      values (new.id,
              case when tg_op = 'INSERT' then 'opening' when v_inv is not null then 'return' else 'adjustment' end,
              coalesce(new.supplier, ''), current_date, v_remaining, v_remaining, new.buying_price)
      returning id into v_batch;
      insert into public.accessory_stock_movements (product_id, batch_id, kind, qty, unit_cost, invoice_no, note)
      values (new.id, v_batch,
              case when tg_op = 'INSERT' then 'opening' when v_inv is not null then 'void_return' else 'adjustment_in' end,
              v_remaining, new.buying_price, v_inv,
              case when tg_op = 'INSERT' then 'Stock entered with the product' when v_inv is not null then 'Sale voided' else 'Stock adjusted' end);
    end if;
  else
    -- Out: oldest batch first.
    v_remaining := -v_delta;
    for v_b in
      select id, qty_available, unit_cost from public.accessory_batches
       where product_id = new.id and qty_available > 0 and status <> 'Reversed'
       order by received_on, id
       for update
    loop
      exit when v_remaining <= 0;
      v_take := least(v_remaining, v_b.qty_available);
      update public.accessory_batches set qty_available = qty_available - v_take where id = v_b.id;
      insert into public.accessory_stock_movements (product_id, batch_id, kind, qty, unit_cost, sale_key, note)
      values (new.id, v_b.id, case when v_reason = 'sale' then 'sale' else 'adjustment_out' end, -v_take, v_b.unit_cost, v_key,
              case when v_reason = 'sale' then '' else 'Stock adjusted' end);
      v_remaining := v_remaining - v_take;
    end loop;
    -- Stock that no batch accounts for (shouldn't happen after the opening
    -- batches below, but the count must still be recorded).
    if v_remaining > 0 then
      insert into public.accessory_stock_movements (product_id, kind, qty, unit_cost, sale_key, note)
      values (new.id, case when v_reason = 'sale' then 'sale' else 'adjustment_out' end, -v_remaining, new.buying_price, v_key, 'No batch to take it from');
    end if;
  end if;
  return new;
end $$;

-- Opening batches for what is on the shelf today — before the trigger, so
-- they're written once.
insert into public.accessory_batches (product_id, source, supplier_name, received_on, qty_received, qty_available, unit_cost)
select p.id, 'opening', coalesce(p.supplier, ''), current_date, p.stock, p.stock, p.buying_price
  from public.accessory_products p
 where p.stock > 0
   and not exists (select 1 from public.accessory_batches b where b.product_id = p.id);

insert into public.accessory_stock_movements (product_id, batch_id, kind, qty, unit_cost, note)
select b.product_id, b.id, 'opening', b.qty_received, b.unit_cost, 'Stock on hand when batches began'
  from public.accessory_batches b
 where b.source = 'opening'
   and not exists (select 1 from public.accessory_stock_movements m where m.batch_id = b.id);

drop trigger if exists trg_accessory_stock_batches on public.accessory_products;
create trigger trg_accessory_stock_batches
  after insert or update of stock on public.accessory_products
  for each row execute function public.tg_accessory_stock_batches();

-- ── Checkout: same function, now tagging the sale ───────────────────────────
-- p_sale_key ties the stock movements this sale makes to the sales row the
-- app inserts next (see trg_sales_link_movements). The one-argument call the
-- device-sale functions make still works through the default.
drop function if exists public.sell_accessory_stock(jsonb);
create or replace function public.sell_accessory_stock(p_items jsonb, p_sale_key uuid default null)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  item record;
begin
  if not public.is_staff() then
    raise exception 'Not authorised to sell accessories';
  end if;

  perform set_config('mm.stock_reason', 'sale', true);
  perform set_config('mm.sale_key', coalesce(p_sale_key::text, ''), true);

  for item in
    select (elem ->> 'id')::bigint as id, (elem ->> 'qty')::integer as qty
    from jsonb_array_elements(p_items) as elem
  loop
    if item.id is null or item.qty is null or item.qty <= 0 then
      raise exception 'Invalid cart line: %', item;
    end if;

    update public.accessory_products
       set stock = stock - item.qty
     where id = item.id
       and stock >= item.qty;

    if not found then
      raise exception 'Not enough stock for product % (need %)', item.id, item.qty;
    end if;
  end loop;

  perform set_config('mm.stock_reason', '', true);
  perform set_config('mm.sale_key', '', true);
end $$;

