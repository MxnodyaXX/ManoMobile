-- ============================================================================
-- Mano Mobile — supplier invoices, purchase batches, stock movements, payments
--
-- Until now a delivery from a supplier left no record at all. Stock Receiving
-- and Admin -> Purchase Orders held their lists in React state, gone on the
-- next refresh, so nobody could answer "what do we owe Matrix?", "what did
-- this charger cost us last time?" or "which delivery did this unit come in?".
--
-- ── The model ───────────────────────────────────────────────────────────────
--   purchase_invoices          the supplier's bill (header). Draft -> Open -> Void.
--   purchase_invoice_items     its lines: an existing product, or a new one
--                              described in new_product until the invoice is
--                              finalised and the product is created.
--   purchase_receipts          one row per delivery actually taken in. Saving
--                              or finalising an invoice never moves stock —
--                              only receiving does, and a bill can arrive in
--                              several deliveries.
--   accessory_batches          every lot of stock: what it cost, from whom, on
--                              which invoice, under what warranty, and how many
--                              of it are still on the shelf. One product, many
--                              batches — the product keeps its id, code and
--                              barcodes; stock = what its batches hold.
--   accessory_stock_movements  every change to stock, signed, with the batch
--                              and the unit cost it moved at. The audit trail
--                              and the basis for FIFO cost of goods sold.
--   supplier_payments          money paid to a supplier, allocated across one
--   + _allocations             or more of their invoices.
--   purchase_invoice_events    who did what to an invoice, when.
--
-- ── Keeping batches in step with stock ──────────────────────────────────────
-- accessory_products.stock stays the number every screen reads. Batches are
-- kept in step by a trigger on it, so nothing that already changes stock
-- (the product form, Stock adjust, checkout, voiding a sale, the device-sale
-- functions) needed rewriting:
--   * stock goes down -> taken from the oldest batches first (FIFO);
--   * stock goes up   -> a voided sale goes back to the batches it came from;
--                        anything else becomes an "adjustment" batch;
--   * the purchasing functions below create their own batches and tell the
--     trigger to stand aside (mm.stock_source = 'managed').
-- Stock on hand when this runs becomes one "opening" batch per product.
--
-- Writes go only through the security-definer functions; the tables have no
-- insert/update policies of their own, so nothing can half-record a delivery.
-- ============================================================================

create sequence if not exists public.accessory_batch_no_seq;
create sequence if not exists public.purchase_invoice_ref_seq;
create sequence if not exists public.supplier_payment_ref_seq;

